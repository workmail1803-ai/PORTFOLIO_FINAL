/**
 * Turns the camera moves generated from the room painting into the site's
 * page transitions: every page is a corner of the same room.
 *
 * For each corner:
 *   public/room/move-<corner>.{webm,mp4}       the room to the corner, under a second
 *   public/room/move-<corner>-back.{webm,mp4}  the same move reversed, for leaving
 *   public/room/corner-<corner>-{1280,1920}.webp   where the camera comes to rest
 *   src/room/corners.ts                  which corners exist
 *
 * The source clips run about ten seconds; the move is sped up with frame
 * blending, so it reads as a quick glide with natural motion blur rather than
 * a jumpy fast-forward. Audio is dropped. Needs ffmpeg on PATH.
 *
 * Source: design-src/video/ (git-ignored).
 */
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import sharp from 'sharp';

const OUT = 'public/room';
const TMP = 'artifacts/room-video';
await mkdir(OUT, { recursive: true });
await mkdir(TMP, { recursive: true });

/**
 * `end` is where the camera has settled on the corner (the generated clips
 * cross-fade into a cleaner close-up just before it); `seconds` is how long
 * the glide lasts on the site.
 */
const CORNERS = [
  { id: 'desk', src: 'design-src/video/move_desk.mp4', end: 7.7, seconds: 1.0 },
  { id: 'shelf', src: 'design-src/video/move-shelf.mp4', end: 6.8, seconds: 0.95 },
];

const ffmpeg = args => execFileSync('ffmpeg', ['-v', 'error', '-y', ...args], { stdio: 'inherit' });
const size = async file => (await readFile(file)).length;

for (const c of CORNERS) {
  const speed = c.end / c.seconds;
  // Five source frames per output frame, then retimed: a 300° shutter, roughly.
  const blur = `tmix=frames=5,setpts=PTS/${speed.toFixed(3)},fps=30,scale=1280:720:flags=lanczos,format=yuv420p`;
  const encode = ['-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '23', '-movflags', '+faststart'];

  // VP9 WebM where the browser plays it, H.264 MP4 everywhere else.
  const webm = ['-an', '-c:v', 'libvpx-vp9', '-crf', '36', '-b:v', '0', '-row-mt', '1', '-deadline', 'good', '-cpu-used', '2'];
  for (const [suffix, reverse] of [['', ''], ['-back', 'reverse,']]) {
    const vf = `trim=0:${c.end},setpts=PTS-STARTPTS,${reverse}${blur}`;
    ffmpeg(['-i', c.src, '-vf', vf, ...encode, `${OUT}/move-${c.id}${suffix}.mp4`]);
    ffmpeg(['-i', c.src, '-vf', vf, ...webm, `${OUT}/move-${c.id}${suffix}.webm`]);
  }

  // The resting frame, unblurred, straight from the source.
  const still = `${TMP}/${c.id}.png`;
  ffmpeg(['-ss', String(c.end), '-i', c.src, '-frames:v', '1', still]);
  await sharp(still).webp({ quality: 80, effort: 6 }).toFile(`${OUT}/corner-${c.id}-1280.webp`);
  await sharp(still).resize(1920, 1080, { kernel: 'lanczos3' }).sharpen({ sigma: 0.8 }).webp({ quality: 78, effort: 6 }).toFile(`${OUT}/corner-${c.id}-1920.webp`);

  const kb = async f => `${Math.round((await size(f)) / 1024)} KB`;
  console.log(
    `${c.id}: move ${await kb(`${OUT}/move-${c.id}.webm`)} webm / ${await kb(`${OUT}/move-${c.id}.mp4`)} mp4, still ${await kb(`${OUT}/corner-${c.id}-1920.webp`)} (${speed.toFixed(1)}× speed)`,
  );
}

await writeFile(
  'src/room/corners.ts',
  `// Generated by scripts/build-room-video.mjs — do not edit by hand.

/** Corners of the room that have a camera move and a resting frame. */
export const CORNERS = ${JSON.stringify(CORNERS.map(c => ({ id: c.id, seconds: c.seconds })))} as const;
export type CornerId = 'room' | (typeof CORNERS)[number]['id'];
`,
);
await rm(TMP, { recursive: true, force: true });
